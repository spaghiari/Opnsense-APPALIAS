"""Branchement automatique d'Unbound, domaine par domaine (opt-in).

Pour chaque nom distinct des règles « domain: » et « full: » des applications
activées, une zone de transfert vers le relais :

    forward-zone:
      name: "<nom>."
      forward-addr: <listen_address>@<listen_port>
      forward-first: yes

« forward-first » : si le relais est arrêté ou planté, Unbound se rabat,
pour ces domaines, sur une récursion directe vers les serveurs faisant
autorité (DNS en clair, port 53 ; dernier recours d'iterator.c), qui contourne
DNS over TLS et le transfert « . ». Port 53 sortant bloqué : SERVFAIL tant que
le relais est arrêté. Pendant la panne, leurs adresses n'entrent pas dans les
alias (voir root_forward_active).

« full:x » donne aussi une zone « x », qui couvre ses sous-domaines : c'est
un sur-ensemble (le relais voit passer ces réponses de plus, seules celles qui
correspondent aux règles remplissent les alias). Une zone couvrant tout son
sous-arbre, le garde-fou des plateformes partagées et des domaines de premier
niveau s'applique aussi aux « full: ». Rien pour « keyword: » ni « regexp: ».

Dédoublonnage : une zone en double est ignorée par Unbound (la première
chargée gagne), le transfert vers le relais pourrait donc disparaître sans
bruit. Un nom est écarté, avec sa raison, quand il est
- invalide à la revalidation (« invalid », défense en profondeur) ;
- refusé par le garde-fou (« shared », « tld ») ;
- déjà une zone de la configuration Unbound d'OPNsense : entrée « dots » avec
  un domaine non vide, de type DNS over TLS ou Forward (Query Forwarding et
  overrides de domaine migrés), activée ou non, puisqu'une entrée désactivée
  peut être réactivée sans nous (« unbound_zone ») ;
- sous-domaine d'une telle zone, qui garde la main sur sa branche
  (« unbound_covered ») ;
- un nom local, ou sous un nom local : domaine du système, noms des host
  overrides et de leurs alias, anciens overrides de domaine, noms à usage
  spécial (localhost, local, lan, home.arpa, internal, arpa, invalid, onion,
  test) (« local ») ;
- sous-domaine d'une zone déjà retenue (« merged », fusion enfant/parent).
Boucle : si l'amont du relais (principal ou de secours) est une adresse du
pare-feu (interfaces, VIP) ou de bouclage, sur le port 53, le port 853
(DNS over TLS), celui d'Unbound ou celui du relais lui-même, aucune zone
n'est produite (« loop »), quel que soit le protocole de l'amont (DNS clair
ou DNS over TLS).

Transfert « . » actif (root_forward_active) : entrée « dots » activée sans
domaine, ou « Use System Nameservers » (unboundplus.forwarding.enabled).

Unbound ne lit le fichier qu'à son démarrage (start.sh le copie dans
/var/unbound/etc/) : la prise en compte passe par un redémarrage, fait
seulement sur « Apply » et seulement quand le contenu a changé.
"""

import ipaddress
import os
import subprocess

from . import shared
from .matcher import KIND_DOMAIN, KIND_FULL, parse_rule
from .v2fly import HOST_RE

CONF_PATH = "/usr/local/etc/unbound.opnsense.d/appalias.conf"
RUNTIME_PATH = "/var/unbound/etc/appalias.conf"
STATUS_PATH = "/var/db/appalias/unbound.json"
CONFIGCTL = "/usr/local/sbin/configctl"
RESTART_TIMEOUT = 120

SPECIAL_USE = ("localhost", "local", "lan", "home.arpa", "internal", "arpa", "invalid", "onion", "test")

HEADER = (
    "# Generated by os-appalias (Services > AppAlias): do not edit.\n"
    "# One forward zone per application domain, to the appaliasd relay.\n"
)

REASONS = {
    "invalid": "invalid name",
    "shared": "shared platform or parent of one (use a dedicated sub-domain)",
    "tld": "top-level domain alone",
    "unbound_zone": "already a zone in Unbound (Query Forwarding or DNS over TLS)",
    "unbound_covered": "under a zone already forwarded by Unbound",
    "local": "local name (system domain, host override or special-use name)",
    "merged": "covered by a parent zone of the relay",
    "loop": "the relay upstream is this firewall (interface, VIP or loopback address): loop",
}


def norm(name):
    name = str(name or "").strip().lower().rstrip(".")
    if name.startswith("*."):
        name = name[2:]
    return name


def is_under(name, parent):
    """Vrai si name est égal à parent ou sous-domaine de parent."""
    return name == parent or name.endswith("." + parent)


def first_match(name, names):
    """Nom le plus précis de names qui couvre name (égal ou parent), ou None."""
    for other in sorted(names, key=lambda n: (-len(n), n)):
        if is_under(name, other):
            return other
    return None


def valid_name(name):
    return 0 < len(name) <= 253 and HOST_RE.match(name) is not None


def unbound_zones(unbound):
    """Domaines non vides des entrées « dots » (toutes, activées ou non)."""
    out = set()
    for dot in (unbound or {}).get("dots") or ():
        if isinstance(dot, dict):
            name = norm(dot.get("domain"))
            if name:
                out.add(name)
    return out


def root_forward_active(unbound):
    """Vrai si Unbound transfère « . » : « Use System Nameservers » coché
    (forwarding), ou entrée « dots » activée sans domaine (DoT ou Forward)."""
    if (unbound or {}).get("forwarding") is True:
        return True
    for dot in (unbound or {}).get("dots") or ():
        if isinstance(dot, dict) and not norm(dot.get("domain")) and dot.get("enabled") \
                and dot.get("type") in ("dot", "forward"):
            return True
    return False


def local_names(unbound):
    out = set(SPECIAL_USE)
    for item in (unbound or {}).get("local_domains") or ():
        name = norm(item)
        if name:
            out.add(name)
    return out


def local_addresses(unbound):
    out = set()
    for item in (unbound or {}).get("local_addresses") or ():
        try:
            out.add(ipaddress.ip_address(str(item).split("%", 1)[0]))
        except ValueError:
            continue
    return out


def is_loop(cfg, unbound):
    """L'amont principal ou de secours est-il ce pare-feu ?

    Ports surveillés, quel que soit le protocole de l'amont : 53, 853 (DNS
    over TLS), celui d'Unbound et celui d'écoute du relais.
    """
    try:
        port = int((unbound or {}).get("port") or 53)
    except (TypeError, ValueError):
        port = 53
    ports = {53, 853, port, cfg.listen_port}
    mine = local_addresses(unbound)
    for host, up_port, _name in cfg.upstreams:
        try:
            ip = ipaddress.ip_address(host)
        except ValueError:
            continue
        if up_port in ports and (ip.is_loopback or ip.is_unspecified or ip in mine):
            return True
    return False


def plan(cfg, platforms=None):
    """Renvoie (zones triées, conflits [{name, apps, reason, detail}], actif)."""
    unbound = cfg.unbound or {}
    if not cfg.enabled or not cfg.unbound_autoforward:
        return [], [], False
    platforms = shared.load(extra=cfg.shared_platforms_extra) if platforms is None else platforms
    conflicts = []

    candidates = {}
    for app in cfg.apps:
        if not app.enabled:
            continue
        for rule in app.domains:
            parsed = parse_rule(rule)
            if parsed is None or parsed[0] not in (KIND_DOMAIN, KIND_FULL):
                continue
            name = norm(parsed[1])
            if not valid_name(name):
                conflicts.append({"name": name, "apps": [app.name], "reason": "invalid", "detail": ""})
                continue
            # Une zone couvre tout le sous-arbre : garde-fou appliqué aussi à full:.
            refusal = shared.refused(KIND_DOMAIN, name, platforms)
            if refusal is not None:
                conflicts.append({"name": name, "apps": [app.name], "reason": refusal, "detail": ""})
                continue
            candidates.setdefault(name, set()).add(app.name)

    if is_loop(cfg, unbound):
        if candidates:
            conflicts.append({"name": "*", "apps": sorted({a for s in candidates.values() for a in s}),
                              "reason": "loop", "detail": ""})
        return [], conflicts, True

    zones_ub = unbound_zones(unbound)
    locals_ = local_names(unbound)
    kept = []
    # Parents d'abord : un enfant d'une zone retenue est fusionné.
    for name in sorted(candidates, key=lambda n: (n.count("."), n)):
        apps = sorted(candidates[name])
        if name in zones_ub:
            conflicts.append({"name": name, "apps": apps, "reason": "unbound_zone", "detail": name})
            continue
        parent = first_match(name, zones_ub)
        if parent is not None:
            conflicts.append({"name": name, "apps": apps, "reason": "unbound_covered", "detail": parent})
            continue
        local = first_match(name, locals_)
        if local is not None:
            conflicts.append({"name": name, "apps": apps, "reason": "local", "detail": local})
            continue
        parent = first_match(name, kept)
        if parent is not None:
            conflicts.append({"name": name, "apps": apps, "reason": "merged", "detail": parent})
            continue
        kept.append(name)
    conflicts.sort(key=lambda c: (c["reason"], c["name"]))
    return sorted(kept), conflicts, True


def forward_addr(cfg):
    return "%s@%d" % (cfg.listen_address, cfg.listen_port)


def is_loopback(address):
    try:
        return ipaddress.ip_address(address).is_loopback
    except ValueError:
        return False


def render(zones, listen_address, port):
    """Contenu du fichier (vide si aucune zone). Noms revalidés avant écriture."""
    zones = [z for z in zones if valid_name(z)]
    if not zones:
        return ""
    out = [HEADER, "server:\n"]
    if is_loopback(listen_address):
        out.append("  do-not-query-localhost: no\n")
    addr = "%s@%d" % (listen_address, port)
    for name in zones:
        out.append("\nforward-zone:\n  name: \"%s.\"\n  forward-addr: %s\n  forward-first: yes\n" % (name, addr))
    return "".join(out)


def parse_zones(text):
    """Zones (sans point final) d'un fichier produit par render()."""
    out = []
    for line in str(text or "").splitlines():
        line = line.strip()
        if line.startswith("name:"):
            name = norm(line[len("name:"):].strip().strip('"'))
            if name:
                out.append(name)
    return out


def read_text(path):
    try:
        with open(path, "r", encoding="utf-8") as fh:
            return fh.read()
    except OSError:
        return ""


def write_atomic(path, text):
    directory = os.path.dirname(path)
    if not os.path.isdir(directory):
        os.makedirs(directory, 0o755, exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    os.chmod(tmp, 0o644)
    os.replace(tmp, path)


def remove_file(path):
    try:
        os.unlink(path)
    except FileNotFoundError:
        pass


def restart_unbound(runner=None):
    """« configctl unbound restart » (restart propre du core) -> (ok, sortie)."""
    runner = runner or subprocess.run
    try:
        proc = runner([CONFIGCTL, "unbound", "restart"], capture_output=True, text=True,
                      timeout=RESTART_TIMEOUT)
    except (OSError, subprocess.SubprocessError) as exc:
        return False, str(exc)
    output = ((proc.stdout or "") + (proc.stderr or "")).strip()
    return proc.returncode == 0 and output.splitlines()[-1:] == ["OK"], output
